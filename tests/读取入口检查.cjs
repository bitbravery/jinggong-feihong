assert(live.includes('readFlows(n)'),'流程页按页数读取');
assert(live.includes('function mergeParsed')&&/if\(isFlow\)records\.flow=\[\.\.\.others,\.\.\.rows\]/.test(live),'流程读取必须按分类合并，不能整块替换（否则读已办会冲掉待办）');
